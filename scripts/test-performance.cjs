const assert=require('node:assert/strict');
(async()=>{
  const {rememberIcon,ICON_CACHE_LIMIT}=await import('../src/iconCache.ts');
  const {sameRows,createKeyedTaskQueue}=await import('../src/performanceHelpers.ts');
  let cache={};
  for(let i=0;i<2000;i++)cache=rememberIcon(cache,`icon${i}`,'data:image/png;base64,abc');
  assert.equal(Object.keys(cache).length,ICON_CACHE_LIMIT);
  assert.equal(cache.icon0,undefined);assert.ok(cache.icon1999);
  cache=rememberIcon(cache,'large','x'.repeat(5*1024*1024));
  cache=rememberIcon(cache,'large2','x'.repeat(5*1024*1024));
  assert.ok(Object.entries(cache).reduce((total,[key,value])=>total+2*(key.length+value.length),0)<=16*1024*1024);
  assert.equal(cache.large,undefined);assert.ok(cache.large2);
  assert.equal(rememberIcon(cache,'oversized','x'.repeat(9*1024*1024)),cache);
  assert.equal(sameRows([{id:1,title:'same'}],[{id:1,title:'same'}]),true);
  assert.equal(sameRows([{id:1,title:'old'}],[{id:1,title:'new'}]),false);
  assert.equal(sameRows([{id:1}],[{id:2}]),false);
  assert.equal(sameRows([{id:1}],[{id:1},{id:2}]),false);
  const queue=createKeyedTaskQueue();
  let stored=null,active=0,peak=0;
  const order=[];
  const save=(style,delay)=>queue(1,async()=>{
    active++;peak=Math.max(peak,active);
    await new Promise(resolve=>setTimeout(resolve,delay));
    stored=style;order.push(style);active--;
  });
  const red={color:'#ff0000',bold:false};
  const blueBold={color:'#0000ff',bold:true};
  await Promise.all([save(red,35),save(blueBold,1)]);
  assert.deepEqual(order,[red,blueBold],'same-card writes must retain interaction order');
  assert.equal(peak,1);
  assert.equal(stored,blueBold,'latest color/bold must be persisted');
  const reset={color:'',bold:false};
  await Promise.all([save(red,5),save(blueBold,1),save(reset,0)]);
  assert.equal(stored,reset,'reset must not be overwritten by an earlier operation');
  const rejected=assert.rejects(queue(1,async()=>{throw new Error('simulated save failure');}),/simulated save failure/);
  const recovered=save(blueBold,0);
  await Promise.all([rejected,recovered]);
  assert.equal(stored,blueBold,'a failed write must not block later saves');
  let unblock;
  const blocked=queue(1,()=>new Promise(resolve=>{unblock=resolve;}));
  await queue(2,async()=>{order.push('other-card');});
  assert.equal(order.at(-1),'other-card','unrelated cards must not wait for this card');
  unblock();await blocked;
  console.log('Performance checks passed: bounded icon count/bytes, unchanged rows, ordered style writes, reset, failure recovery, independent cards.');
})().catch(error=>{console.error(error);process.exitCode=1;});
